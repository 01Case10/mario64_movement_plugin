#!/usr/bin/env python3
"""Generate crates/stepkit-core/src/anim_table.rs from the decomp's
assets/anims/anim_*.inc.c headers and include/mario_animation_ids.h
(plan §4.5 AN-01).

Reuses the header parsing from oracle/gen_anim_table.py (the same parser
the oracle's own C table is built with), so the Rust table and the
oracle's gOracleAnimTable can never disagree on values.

The generated file is checked in so the crate builds without the decomp
checkout (oracle/sm64/ is git-ignored). Re-run this script after changing
the pinned decomp commit (oracle/DECOMP_COMMIT); a unit test in anim.rs
re-validates the checked-in tables against the decomp source whenever the
checkout is present.
"""

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
IDS_H = REPO / "oracle" / "sm64" / "include" / "mario_animation_ids.h"
OUT = REPO / "crates" / "stepkit-core" / "src" / "anim_table.rs"


def parse_headers(decomp_dir: Path) -> dict[int, tuple[int, int, int, int, int]]:
    """Same parse as oracle/gen_anim_table.py: first 5 integer literals of
    each `static const struct Animation anim_<hex>[]` are
    (flags, animYTransDivisor, startFrame, loopStart, loopEnd).

    The regexes are copied from oracle/gen_anim_table.py so both tables
    share one parsing rule; the oracle's own C table is generated by that
    script, so the values cannot disagree."""
    array_re = re.compile(r"static const struct Animation (anim_[0-9A-Fa-f]+)\[\] = \{")
    int_re = re.compile(r"-?(?:0[xX][0-9A-Fa-f]+|\d+)")
    headers: dict[int, tuple[int, int, int, int, int]] = {}
    for path in sorted(decomp_dir.glob("assets/anims/anim_*.inc.c")):
        text = path.read_text()
        for m in array_re.finditer(text):
            name = m.group(1)
            anim_id = int(name[len("anim_"):], 16)
            vals = int_re.findall(text, m.end(), m.end() + 512)[:5]
            if len(vals) != 5:
                sys.exit(f"{path}: {name}: found {len(vals)} header ints, expected 5")
            headers[anim_id] = tuple(int(v, 0) for v in vals)  # type: ignore[assignment]
    return headers


def parse_ids() -> list[tuple[str, int]]:
    """Parse `enum MarioAnimID` from mario_animation_ids.h into
    (NAME, value) in enum order."""
    text = IDS_H.read_text()
    body = text.split("enum MarioAnimID {", 1)[1].split("}", 1)[0]
    ids: list[tuple[str, int]] = []
    value = 0
    for line in body.splitlines():
        # Strip both comment styles, then the trailing comma.
        line = re.sub(r"/\*.*?\*/", "", line).split("//", 1)[0].strip().rstrip(",").strip()
        if not line:
            continue
        if "=" in line:
            name, val = (p.strip() for p in line.split("=", 1))
            value = int(val, 0)
        else:
            name = line
        if not re.fullmatch(r"[A-Z][A-Z0-9_]*", name):
            sys.exit(f"unparseable enum line: {line!r}")
        ids.append((name, value))
        value += 1
    return ids


def main() -> None:
    decomp_dir = REPO / "oracle" / "sm64"
    if not decomp_dir.is_dir():
        sys.exit(f"decomp checkout not found: {decomp_dir} (clone per oracle/README.md)")
    if not IDS_H.is_file():
        sys.exit(f"animation ids header not found: {IDS_H}")

    headers = parse_headers(decomp_dir)
    if not headers:
        sys.exit("no animation headers found")
    ids = parse_ids()

    max_id = max(headers)
    if max_id >= len(ids):
        sys.exit(f"header id {max_id} has no MARIO_ANIM_* name")

    lines: list[str] = []
    lines.append("//! Animation headers and ids ported from the decomp.")
    lines.append("//!")
    lines.append("//! DO NOT EDIT BY HAND. Regenerate with `tools/gen_anim_table.py`")
    lines.append("//! (decomp commit pinned in `oracle/DECOMP_COMMIT`).")
    lines.append("//!")
    lines.append("//! Headers: `assets/anims/anim_*.inc.c` (the 5-s16 header of each")
    lines.append("//! `struct Animation`: flags, animYTransDivisor, startFrame, loopStart,")
    lines.append("//! loopEnd). Ids: `include/mario_animation_ids.h` (`enum MarioAnimID`;")
    lines.append("//! the hex suffix of the anim array name is the id).")
    lines.append("//! See `crate::anim` for the ported animation state machine.")
    lines.append("")
    lines.append("/// One animation header.")
    lines.append("/// decomp: `struct Animation` head (`include/types.h`).")
    lines.append("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    lines.append("pub struct AnimHeader {")
    lines.append("    /// `ANIM_FLAG_*` bits (`include/types.h:80-82`).")
    lines.append("    pub flags: i16,")
    lines.append("    /// `animYTransDivisor` (renderer-only; carried for completeness).")
    lines.append("    pub y_trans_divisor: i16,")
    lines.append("    pub start_frame: i16,")
    lines.append("    pub loop_start: i16,")
    lines.append("    pub loop_end: i16,")
    lines.append("}")
    lines.append("")
    lines.append("/// `ANIM_FLAG_*` bits. decomp: `include/types.h:80-82`.")
    lines.append("pub const ANIM_FLAG_NOLOOP: i16 = 1;")
    lines.append("pub const ANIM_FLAG_BACKWARD: i16 = 2;")
    lines.append("pub const ANIM_FLAG_2: i16 = 4;")
    lines.append("")
    lines.append(f"/// Number of animation headers in [`ANIM_TABLE`] (ids 0..{max_id}).")
    lines.append(f"pub const ANIM_COUNT: usize = {max_id + 1};")
    lines.append("")
    lines.append("/// Animation headers indexed by animation id.")
    lines.append("/// decomp: `assets/anims/anim_*.inc.c`.")
    lines.append(f"pub const ANIM_TABLE: [AnimHeader; ANIM_COUNT] = [")
    for i in range(max_id + 1):
        v = headers.get(i, (0, 0, 0, 0, 0))
        lines.append(
            f"    AnimHeader {{ flags: {v[0]}, y_trans_divisor: {v[1]}, "
            f"start_frame: {v[2]}, loop_start: {v[3]}, loop_end: {v[4]} }}, // {i:#04x}"
        )
    lines.append("];")
    lines.append("")
    lines.append("/// Look up an animation header by id.")
    lines.append("///")
    lines.append("/// Mirrors the oracle stub's `load_patchable_table`: out-of-range ids")
    lines.append("/// (including negative ones) fall back to id 0.")
    lines.append("pub fn anim_header(id: i32) -> AnimHeader {")
    lines.append("    if id < 0 || (id as usize) >= ANIM_COUNT {")
    lines.append("        ANIM_TABLE[0]")
    lines.append("    } else {")
    lines.append("        ANIM_TABLE[id as usize]")
    lines.append("    }")
    lines.append("}")
    lines.append("")
    lines.append("/// `MARIO_ANIM_*` ids. decomp: `include/mario_animation_ids.h`.")
    for name, value in ids:
        lines.append(f"pub const {name}: i32 = {value}; // {value:#04x}")
    lines.append("")

    OUT.write_text("\n".join(lines))
    print(f"wrote {len(headers)} headers + {len(ids)} ids to {OUT}")


if __name__ == "__main__":
    main()
