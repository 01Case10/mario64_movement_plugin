#!/usr/bin/env python3
"""Scan decomp anim_*.inc.c files and emit a C snippet with the 5-s16
animation headers (flags, animYTransDivisor, startFrame, loopStart, loopEnd)
indexed by animation id (hex suffix of the array name).

Usage: python3 gen_anim_table.py <decomp_dir> <out_inc>
"""
import glob
import os
import re
import sys


def main():
    decomp_dir, out_inc = sys.argv[1], sys.argv[2]
    array_re = re.compile(r"static const struct Animation (anim_[0-9A-Fa-f]+)\[\] = \{")
    int_re = re.compile(r"-?(?:0[xX][0-9A-Fa-f]+|\d+)")

    headers = {}
    for path in sorted(glob.glob(os.path.join(decomp_dir, "assets", "anims", "anim_*.inc.c"))):
        with open(path) as f:
            text = f.read()
        for m in array_re.finditer(text):
            name = m.group(1)
            anim_id = int(name[len("anim_"):], 16)
            # First 5 integer literals after the opening brace are the header.
            vals = int_re.findall(text, m.end(), m.end() + 512)[:5]
            if len(vals) != 5:
                raise SystemExit(f"{path}: {name}: found {len(vals)} header ints, expected 5")
            headers[anim_id] = [int(v, 0) for v in vals]

    if not headers:
        raise SystemExit("no animation headers found")

    max_id = max(headers)
    rows = []
    for i in range(max_id + 1):
        v = headers.get(i, (0, 0, 0, 0, 0))
        rows.append("    {%d, %d, %d, %d, %d}," % tuple(v))

    with open(out_inc, "w") as f:
        f.write("/* Generated by oracle/gen_anim_table.py - do not edit. */\n")
        f.write("struct OracleAnimHeader { s16 flags; s16 ydiv; s16 start; s16 loopStart; s16 loopEnd; };\n")
        f.write("static const struct OracleAnimHeader gOracleAnimTable[] = {\n")
        f.write("\n".join(rows) + "\n")
        f.write("};\n")
        f.write("static const s32 gOracleAnimCount = %d;\n" % (max_id + 1))
    print(f"wrote {len(headers)} anim headers (ids 0..{max_id}) to {out_inc}")


if __name__ == "__main__":
    main()
