s32 load_patchable_table(struct DmaHandlerList *list, s32 index) {
    if (index < 0 || index >= gOracleAnimCount) {
        index = 0;
    }
    gOracleLastAnimId = index;
    if (list->bufTarget != NULL) {
        /* Copy the 5-s16 header: flags, animYTransDivisor, startFrame,
           loopStart, loopEnd. struct OracleAnimHeader is exactly 5 s16s. */
        memcpy(list->bufTarget, &gOracleAnimTable[index], 5 * sizeof(s16));
    }
    return 0;
}

